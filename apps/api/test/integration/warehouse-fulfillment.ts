import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import test from 'node:test';
import {DatabaseService} from '../../src/database';
import {WarehouseService} from '../../src/warehouses';
import {FulfillmentService} from '../../src/fulfillment';
import {ProductsService} from '../../src/products';
import {BrandPortalService} from '../../src/brand-portal';

test('CP35: atomic multiwarehouse stock, paid-only reservation, scoped batches and internal tracking',async()=>{
 if(!process.env.DATABASE_URL?.includes('127.0.0.1'))
  throw new Error('CP35 integration requires disposable localhost database; refuses remote DB');
 const db=new DatabaseService(),warehouse=new WarehouseService(db),fulfill=new FulfillmentService(db);
 const products=new ProductsService(db),portal=new BrandPortalService(db);
 const suffix=randomUUID().slice(0,7).toUpperCase();
 const admin={id:randomUUID(),email:'warehouse-admin@example.invalid',emailVerified:true};
 const partner={id:randomUUID(),email:'brand-partner@example.invalid',emailVerified:true};
 const customer={id:randomUUID(),email:'buyer@example.invalid',emailVerified:true};
 try{
  const bA=(await db.query<{id:string}>('INSERT INTO product.brands(name,slug) VALUES($1,$2) RETURNING id',['Brand Alpha '+suffix,'brand-alpha-'+suffix.toLowerCase()])).rows[0];
  const bB=(await db.query<{id:string}>('INSERT INTO product.brands(name,slug) VALUES($1,$2) RETURNING id',['Brand Beta '+suffix,'brand-beta-'+suffix.toLowerCase()])).rows[0];
  const a=await products.create({name:'Desk Light '+suffix,slug:'desk-light-'+suffix.toLowerCase(),sku:'CP35-A-'+suffix,category:'home',description:'Reading accessory',price_idr:100000,stock_qty:0,brand_id:bA.id},admin);
  const b=await products.create({name:'Desk Organizer '+suffix,slug:'desk-organizer-'+suffix.toLowerCase(),sku:'CP35-B-'+suffix,category:'home',description:'Office accessory',price_idr:80000,stock_qty:0,brand_id:bB.id},admin);
  await assert.rejects(()=>products.create({name:'Stocked in nowhere',slug:'no-location-'+suffix.toLowerCase(),category:'home',price_idr:500,stock_qty:5},admin),/Stok awal/);
  const wa=(await warehouse.create(admin,{code:'CP35A-'+suffix,name:'Warehouse Test A',address:'Jl. Teknologi 12, Unit A',city:'Bandung',province:'Jawa Barat',postalCode:'40115'})).warehouse;
  const wb=(await warehouse.create(admin,{code:'CP35B-'+suffix,name:'Warehouse Test B',address:'Jl. Teknologi 12, Unit B',city:'Bandung',province:'Jawa Barat',postalCode:'40115'})).warehouse;
  const receipt=async(warehouseId:string,productId:string,qty:number,key:string)=>warehouse.adjust(admin,{warehouseId,productId,delta:qty,reason:'receipt',notes:'Integration stock receipt document #42',idempotencyKey:key});
  await receipt(wa.id,a.id,2,randomUUID());
  await receipt(wb.id,a.id,5,randomUUID());
  await receipt(wb.id,b.id,4,randomUUID());
  let cache=await db.query<{stock_qty:number}>('SELECT stock_qty FROM product.products WHERE id=$1',[a.id]);
  assert.equal(cache.rows[0].stock_qty,0,'dispatch-disabled warehouse stock must never be sellable');
  await warehouse.update(admin,wa.id,{dispatchEnabled:true});
  await warehouse.update(admin,wb.id,{dispatchEnabled:true});
  cache=await db.query('SELECT stock_qty FROM product.products WHERE id=$1',[a.id]);
  assert.equal(cache.rows[0].stock_qty,7);
  const key=randomUUID();
  const transfer={fromWarehouseId:wa.id,toWarehouseId:wb.id,productId:a.id,quantity:1,notes:'Physical transfer counted at both warehouse locations',idempotencyKey:key};
  const first=await warehouse.transfer(admin,transfer),again=await warehouse.transfer(admin,transfer);
  assert.equal(first.replayed,false);assert.equal(again.replayed,true);
  await assert.rejects(()=>warehouse.transfer(admin,{...transfer,quantity:2}),/Transfer key/);
  cache=await db.query('SELECT stock_qty FROM product.products WHERE id=$1',[a.id]);
  assert.equal(cache.rows[0].stock_qty,7,'transfer must conserve total saleable stock');
  const initial=await warehouse.list();assert.ok(initial.stock.some((x:any)=>x.product_id===a.id&&x.warehouse_id===wb.id&&x.on_hand===6));
  // Create a fake order ONLY inside disposable CI database: never a real charge.
  const orderId=randomUUID();
  await db.query("INSERT INTO product.orders(id,customer_user_id,status,payment_status) VALUES($1,$2,'draft','not_initiated')",[orderId,customer.id]);
  await db.query('INSERT INTO product.order_items(order_id,product_id,brand_id,quantity,unit_price_idr,product_name,sku) VALUES($1,$2,$3,4,100000,$4,$5)',
   [orderId,a.id,bA.id,a.name,a.sku]);
  await db.query('INSERT INTO product.order_items(order_id,product_id,brand_id,quantity,unit_price_idr,product_name,sku) VALUES($1,$2,$3,2,80000,$4,$5)',
   [orderId,b.id,bB.id,b.name,b.sku]);
  const requestKey=randomUUID();
  await assert.rejects(()=>fulfill.prepare(admin,orderId,{idempotencyKey:requestKey}),/Cannot reserve a draft/);
  const before=await db.query<{reserved:number}>('SELECT coalesce(sum(reserved),0)::integer AS reserved FROM product.warehouse_stock');
  assert.equal(before.rows[0].reserved,0);
  await db.query("UPDATE product.orders SET status='paid',payment_status='paid',payment_provider='ci-fixture-only',payment_reference=$2 WHERE id=$1",
   [orderId,'verified-ci-'+suffix]);
  const prepared=await fulfill.prepare(admin,orderId,{idempotencyKey:requestKey});
  assert.equal(prepared.replayed,false);
  assert.equal(prepared.batches.length,3,'split brand A across two warehouses and brand B at second');
  const repeat=await fulfill.prepare(admin,orderId,{idempotencyKey:requestKey});
  assert.equal(repeat.replayed,true);assert.equal(repeat.batches.length,3);
  await assert.rejects(()=>fulfill.prepare(admin,orderId,{idempotencyKey:randomUUID()}),/different request key/);
  const bCount=await db.query<{n:number}>('SELECT count(*)::integer n FROM product.fulfillment_batches WHERE order_id=$1',[orderId]);
  assert.equal(bCount.rows[0].n,3);
  let aa=await db.query<{stock_qty:number}>('SELECT stock_qty FROM product.products WHERE id=$1',[a.id]);
  let bb=await db.query<{stock_qty:number}>('SELECT stock_qty FROM product.products WHERE id=$1',[b.id]);
  assert.equal(aa.rows[0].stock_qty,3);assert.equal(bb.rows[0].stock_qty,2);
  await assert.rejects(()=>warehouse.update(admin,wa.id,{dispatchEnabled:false}),/Release all fulfillment/);
  await assert.rejects(()=>warehouse.adjust(admin,{warehouseId:wa.id,productId:a.id,delta:-2,reason:'adjustment',notes:'Attempt to consume reserved inventory',idempotencyKey:randomUUID()}),/balance insufficient/);
  const order2=randomUUID();
  await db.query("INSERT INTO product.orders(id,customer_user_id,status,payment_status,payment_provider,payment_reference) VALUES($1,$2,'paid','paid','ci-fixture-only',$3)",[order2,customer.id,'verified-ci-2-'+suffix]);
  await db.query('INSERT INTO product.order_items(order_id,product_id,brand_id,quantity,unit_price_idr,product_name) VALUES($1,$2,$3,99,100000,$4)',[order2,a.id,bA.id,a.name]);
  await assert.rejects(()=>fulfill.prepare(admin,order2,{idempotencyKey:randomUUID()}),/Insufficient dispatch-enabled/);
  const afterFailed=await db.query<{stock_qty:number}>('SELECT stock_qty FROM product.products WHERE id=$1',[a.id]);
  assert.equal(afterFailed.rows[0].stock_qty,3,'failed allocation rolls back warehouse reservations');
  await db.query('INSERT INTO product.brand_memberships(brand_id,user_id,role,is_active,added_by) VALUES($1,$2,\'viewer\',true,$3)',[bA.id,partner.id,admin.id]);
  const visible=await portal.warehouseStock(partner,bA.id);
  assert.ok(visible.items.length>0);assert.ok(visible.items.every((x:any)=>x.product_id===a.id));
  await assert.rejects(()=>portal.warehouseStock(partner,bB.id),/Akses brand/);
  const partnerBatches=await portal.fulfillment(partner,bA.id);
  assert.equal(partnerBatches.items.length,2);
  assert.ok(partnerBatches.items.every((x:any)=>!('contact_email' in x)&&!('address_line' in x)));
  const tracking=await fulfill.customerTracking(customer,orderId);
  assert.equal(tracking.batches.length,3);assert.equal(tracking.trackingNumber,null);
  await assert.rejects(()=>fulfill.customerTracking({id:randomUUID(),email:'wrong@example.invalid',emailVerified:true},orderId),/Order not found/);
  const batchA=prepared.batches.find((x:any)=>x.brandId===bA.id);
  assert.ok(batchA);
  await assert.rejects(()=>fulfill.transition(admin,batchA!.id,{state:'packed',notes:'Skip picking invalid'}),/Invalid fulfillment/);
  await fulfill.transition(admin,batchA!.id,{state:'picking',notes:'Picking list checked by warehouse operator'});
  await fulfill.transition(admin,batchA!.id,{state:'packed',notes:'Packing checklist completed'});
  await fulfill.transition(admin,batchA!.id,{state:'ready_for_carrier',notes:'Waiting for authorized courier booking'});
  const timeline=await fulfill.timeline(batchA!.id);
  assert.deepEqual(timeline.events.map((x:any)=>x.state),['reserved','picking','packed','ready_for_carrier']);
  const batchB=prepared.batches.find((x:any)=>x.brandId===bB.id);
  await db.query("UPDATE product.orders SET status='cancelled',payment_status='refunded' WHERE id=$1",[orderId]);
  await assert.rejects(()=>fulfill.transition(admin,batchA!.id,{state:'ready_for_carrier',notes:'Attempt after refund'}),/no longer paid/);
  const released=await fulfill.release(admin,batchB!.id,{notes:'Refund completed and parcel not picked'});
  assert.equal(released.state,'cancelled');assert.equal(released.replayed,false);
  const againRelease=await fulfill.release(admin,batchB!.id,{notes:'Refund completed and parcel not picked'});
  assert.equal(againRelease.replayed,true);
  bb=await db.query('SELECT stock_qty FROM product.products WHERE id=$1',[b.id]);
  assert.equal(bb.rows[0].stock_qty,4,'refunded unpicked reservation releases saleable balance');
  const shipments=await db.query<{n:number}>('SELECT count(*)::integer n FROM product.shipments WHERE order_id=$1',[orderId]);
  assert.equal(shipments.rows[0].n,0,'fulfillment state cannot book a real courier');
 }finally{await db.onModuleDestroy();}
});
